import { z } from 'zod';
import { AgeRating, MovieStatus } from '../enums.js';

/** Limits shared by the API DTOs and the web forms so both validate the same way. */
export const CATALOG_LIMITS = {
  titleMax: 200,
  durationMin: 1,
  /** Minutes. */
  durationMax: 400,
  genresPerMovieMax: 5,
  genreNameMax: 50,
  slugMax: 120,
  searchMax: 100,
  pageSizeMax: 50,
  publicPageSizeDefault: 12,
  adminPageSizeDefault: 20,
  posterMaxBytes: 2 * 1024 * 1024,
  /** Lifetime of the presigned PUT returned by `POST /admin/uploads/poster`. */
  posterUploadTtlSeconds: 5 * 60,
  /** Lifetime of every `posterUrl` (presigned GET). */
  posterUrlTtlSeconds: 60 * 60,
} as const;

/** Poster image types accepted for upload, with the extension used in the object key. */
export const POSTER_CONTENT_TYPES = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
} as const;
export type PosterContentType = keyof typeof POSTER_CONTENT_TYPES;
export const posterContentTypes = Object.keys(POSTER_CONTENT_TYPES) as PosterContentType[];

export const isPosterContentType = (value: string): value is PosterContentType =>
  Object.hasOwn(POSTER_CONTENT_TYPES, value);

export const POSTER_KEY_PREFIX = 'posters/';

/**
 * Keys are generated by the server: `posters/{uuid}.{ext}`. The strict shape also rules out
 * path tricks such as `posters/../users/x` or `posters/a/b.png`.
 */
const POSTER_KEY_PATTERN =
  /^posters\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp)$/;

export function isPosterKey(key: string): boolean {
  return POSTER_KEY_PATTERN.test(key);
}

/** Content type implied by a poster key's extension, or `undefined` for a malformed key. */
export function posterContentTypeOfKey(key: string): PosterContentType | undefined {
  const ext = POSTER_KEY_PATTERN.exec(key)?.[1];
  return posterContentTypes.find((type) => POSTER_CONTENT_TYPES[type] === ext);
}

/** Lower-case ASCII words joined by single hyphens, e.g. `mua-ha-cuoi-cung-2`. */
export const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

const ISO_DATE_PATTERN = /^(\d{4})-(\d{2})-(\d{2})$/;

/** `YYYY-MM-DD` naming a real calendar day (rejects 2026-02-30 and datetimes). */
export function isIsoDate(value: string): boolean {
  const match = ISO_DATE_PATTERN.exec(value);
  if (!match) return false;
  const [, year, month, day] = match.map(Number) as [number, number, number, number];
  const date = new Date(Date.UTC(year, month - 1, day));
  return (
    date.getUTCFullYear() === year && date.getUTCMonth() === month - 1 && date.getUTCDate() === day
  );
}

const hasNoDuplicates = (values: readonly string[]): boolean =>
  new Set(values).size === values.length;

// ─── Requests ───

const titleSchema = z
  .string({ error: 'Vui lòng nhập tên phim' })
  .trim()
  .min(1, { error: 'Vui lòng nhập tên phim' })
  .max(CATALOG_LIMITS.titleMax, { error: `Tên phim tối đa ${CATALOG_LIMITS.titleMax} ký tự` });

const durationSchema = z
  .number({ error: 'Vui lòng nhập thời lượng (phút)' })
  .int({ error: 'Thời lượng phải là số phút nguyên' })
  .min(CATALOG_LIMITS.durationMin, { error: 'Thời lượng tối thiểu 1 phút' })
  .max(CATALOG_LIMITS.durationMax, {
    error: `Thời lượng tối đa ${CATALOG_LIMITS.durationMax} phút`,
  });

const releaseDateSchema = z
  .string({ error: 'Vui lòng chọn ngày khởi chiếu' })
  .refine(isIsoDate, { error: 'Ngày khởi chiếu phải có dạng YYYY-MM-DD' });

const genreIdsSchema = z
  .array(z.uuid({ error: 'Thể loại không hợp lệ' }))
  .max(CATALOG_LIMITS.genresPerMovieMax, {
    error: `Chọn tối đa ${CATALOG_LIMITS.genresPerMovieMax} thể loại`,
  })
  .refine(hasNoDuplicates, { error: 'Thể loại bị trùng' });

/** `null` removes the poster (update only); otherwise a key from `POST /admin/uploads/poster`. */
const posterKeySchema = z.string().max(200).nullable();

export const slugSchema = z
  .string()
  .trim()
  .min(1, { error: 'Vui lòng nhập slug' })
  .max(CATALOG_LIMITS.slugMax, { error: `Slug tối đa ${CATALOG_LIMITS.slugMax} ký tự` })
  .regex(SLUG_PATTERN, { error: 'Slug chỉ gồm chữ thường không dấu, số và dấu gạch ngang' });

/** `POST /admin/movies`. The slug is generated from the title. */
export const createMovieRequestSchema = z.object({
  title: titleSchema,
  duration: durationSchema,
  ageRating: z.enum(AgeRating, { error: 'Vui lòng chọn độ tuổi' }),
  status: z.enum(MovieStatus, { error: 'Trạng thái không hợp lệ' }),
  releaseDate: releaseDateSchema,
  genreIds: genreIdsSchema,
  posterKey: posterKeySchema.optional(),
});

/** `PATCH /admin/movies/:id`: any subset. `slug` is only changed when sent explicitly. */
export const updateMovieRequestSchema = createMovieRequestSchema.partial().extend({
  slug: slugSchema.optional(),
});

export type CreateMovieRequest = z.infer<typeof createMovieRequestSchema>;
export type UpdateMovieRequest = z.infer<typeof updateMovieRequestSchema>;

export const genreRequestSchema = z.object({
  name: z
    .string({ error: 'Vui lòng nhập tên thể loại' })
    .trim()
    .min(1, { error: 'Vui lòng nhập tên thể loại' })
    .max(CATALOG_LIMITS.genreNameMax, {
      error: `Tên thể loại tối đa ${CATALOG_LIMITS.genreNameMax} ký tự`,
    }),
});
export type GenreRequest = z.infer<typeof genreRequestSchema>;

export const posterUploadRequestSchema = z.object({
  contentType: z.enum(posterContentTypes, { error: 'Chỉ nhận ảnh JPEG, PNG hoặc WebP' }),
  sizeBytes: z
    .number()
    .int()
    .min(1, { error: 'Tệp rỗng' })
    .max(CATALOG_LIMITS.posterMaxBytes, { error: 'Ảnh poster tối đa 2 MB' }),
});
export type PosterUploadRequest = z.infer<typeof posterUploadRequestSchema>;

/**
 * Query of `GET /movies` and `GET /admin/movies`. Lenient on purpose so the web app can parse
 * a hand-edited URL: invalid values fall back to their defaults instead of failing.
 */
export const movieListQuerySchema = z.object({
  page: z.coerce.number().int().min(1).catch(1),
  pageSize: z.coerce
    .number()
    .int()
    .min(1)
    .max(CATALOG_LIMITS.pageSizeMax)
    .optional()
    .catch(undefined),
  status: z.enum(MovieStatus).optional().catch(undefined),
  genre: z.string().regex(SLUG_PATTERN).optional().catch(undefined),
  q: z.string().trim().max(CATALOG_LIMITS.searchMax).optional().catch(undefined),
});
export type MovieListQuery = z.infer<typeof movieListQuerySchema>;

// ─── Responses ───

export const genreSchema = z.object({
  id: z.uuid(),
  name: z.string(),
  slug: z.string(),
});
export type Genre = z.infer<typeof genreSchema>;

/** `GET /admin/genres`: with the number of movies using each genre. */
export const adminGenreSchema = genreSchema.extend({ movieCount: z.number().int() });
export type AdminGenre = z.infer<typeof adminGenreSchema>;

export const movieSchema = z.object({
  id: z.uuid(),
  title: z.string(),
  slug: z.string(),
  duration: z.number().int(),
  ageRating: z.enum(AgeRating),
  status: z.enum(MovieStatus),
  /** `YYYY-MM-DD` (a calendar date, no time zone). */
  releaseDate: z.string(),
  /** Presigned GET, valid for `CATALOG_LIMITS.posterUrlTtlSeconds`; `null` without a poster. */
  posterUrl: z.string().nullable(),
  genres: z.array(genreSchema),
});
export type Movie = z.infer<typeof movieSchema>;

/** Admin view: also exposes the storage key so the edit form can keep it. */
export const adminMovieSchema = movieSchema.extend({
  posterKey: z.string().nullable(),
  createdAt: z.string(),
  updatedAt: z.string(),
});
export type AdminMovie = z.infer<typeof adminMovieSchema>;

export const pageSchema = <T extends z.ZodType>(item: T) =>
  z.object({
    items: z.array(item),
    total: z.number().int(),
    page: z.number().int(),
    pageSize: z.number().int(),
  });
export interface Page<T> {
  items: T[];
  total: number;
  page: number;
  pageSize: number;
}

export const posterUploadSchema = z.object({
  key: z.string(),
  uploadUrl: z.string(),
  /** Seconds. */
  expiresIn: z.number().int(),
});
export type PosterUpload = z.infer<typeof posterUploadSchema>;

/** Machine-readable `code` values of catalog API errors. */
